// Command gen-migration-version records the highest SQL migration version in
// the server binary without embedding migration contents.
package main

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
)

var migrationName = regexp.MustCompile(`^(\d+)_.*\.sql$`)

func main() {
	entries, err := os.ReadDir("db/migrations")
	if err != nil {
		fail(err)
	}
	var highest int64
	for _, entry := range entries {
		if entry.IsDir() {
			continue
		}
		match := migrationName.FindStringSubmatch(entry.Name())
		if match == nil {
			continue
		}
		version, err := strconv.ParseInt(match[1], 10, 64)
		if err != nil {
			fail(err)
		}
		if version > highest {
			highest = version
		}
	}
	if highest == 0 {
		fail(fmt.Errorf("no numbered SQL migrations found"))
	}
	content := fmt.Sprintf("// Code generated by cmd/gen-migration-version; DO NOT EDIT.\n\npackage obs\n\nconst ExpectedMigrationVersion int64 = %d\n", highest)
	if err := os.WriteFile("internal/obs/migration_version_gen.go", []byte(content), 0o644); err != nil {
		fail(err)
	}
}

func fail(err error) {
	fmt.Fprintln(os.Stderr, "generate migration version:", err)
	os.Exit(1)
}
